-- Demo-only schema for the Vistula Task Manager assignment.
-- The anon policy makes all rows publicly readable and writable. Use test data only.
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  completed boolean not null default false
);

alter table public.tasks enable row level security;

drop policy if exists "Public demo task access" on public.tasks;
create policy "Public demo task access" on public.tasks
  for all to anon using (true) with check (true);

